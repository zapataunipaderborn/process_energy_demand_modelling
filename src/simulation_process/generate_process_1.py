"""
Sterilization process simulation → data/gold/experiment_1/process_1/datasets/

Produces:
  df_event_log.parquet       – process event log (same schema as process_2)
  df_expanded.parquet        – minute-resolution energy + weather time series
  df_production_plan.parquet – one row per batch

Autoclave heat/hold/cool power curves are generated by the physical model in
`autoclave_function.sterilization_profile` (not a synthetic formula) — one
profile per autoclave cycle, resampled to the discrete-event timestamps.

One plant-level coupling is deliberately built in, because it is what the
downstream models are supposed to discover (see the VOLUME block below):

  batch volume  -> case duration.  `volume_L` scales the duration of every
      station that handles the product volume, INCLUDING the autoclave cycle
      (a bigger load takes longer to come up to sterilization temperature).
      Previously the autoclave — the longest station — ignored volume, so
      volume explained only ~4% of total case duration and no case-duration
      model could beat a constant.

  batch volume  -> autoclave energy levels.  The steam mass flow the operator
      sets on the valve (`m_dot_steam`) and the cooling-water flow
      (`m_dot_cool`) both scale with the charge, so the heat-phase steam
      plateau (m_dot_steam * h_vap) and the cool-phase cooling-water peak are
      predominantly determined by `volume_L`, with only a few percent of
      residual noise on top. Previously both flows were drawn as pure +-18%
      per-cycle noise with no recorded cause, so the plateau of every
      `autoclaving_*_heat` instance varied for reasons no attribute-conditioned
      model could learn — the level models could only predict a constant.

The weather does NOT drive the energy demand of this process
(WEATHER_ENERGY_COUPLING = False): the distillation duty and the autoclave
losses are solved at a fixed ambient temperature (FIXED_AMBIENT_C, applied
through `physics_ambient_c`), so this process is the one where the exogenous
factors carry no signal. The `ef_*` columns are still written to the expanded
frame from the deterministic `weather_at` series as before, so the exogenous
features exist and the models can be run unchanged — they simply have nothing
to find here. Every other process keeps its weather coupling.

NOTE this paragraph described the intended behaviour before the switch existed:
until 2026-07-24 the code passed the real ambient temperature into both the
distillation duty scaling and the autoclave physics, so process_1 WAS weather-
coupled despite the docstring. Datasets generated before that date carry the
coupling and must be regenerated to match this description.
"""

